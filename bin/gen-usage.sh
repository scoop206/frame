#!/usr/bin/env zsh
# gen-usage.sh — regenerate docs/usage.md from `frame --help`.
#
# The header comment block in bin/frame is the single source of truth for the
# usage text; this script wraps that output in a generated markdown page so the
# README can link to the full usage without duplicating it.
#
#   make usage         regenerate docs/usage.md
#   make check-usage   fail if docs/usage.md is stale (used in CI)
set -euo pipefail

REPO_ROOT="${0:A:h:h}"
OUT="$REPO_ROOT/docs/usage.md"

{
  echo "<!-- Generated by bin/gen-usage.sh from \`frame --help\`. Do not edit by hand. -->"
  echo "<!-- Run \`make usage\` to regenerate. -->"
  echo
  echo "# frame — full usage"
  echo
  echo "The complete output of \`frame --help\`, kept current by CI."
  echo
  echo '```text'
  "$REPO_ROOT/bin/frame" --help
  echo '```'
} > "$OUT"

echo "wrote $OUT"
